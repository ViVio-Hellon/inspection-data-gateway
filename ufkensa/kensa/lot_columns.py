#: 書き方が別の名前になっている列の対応(2つ目の列名 → 第1の列名)。見つかったら足す
ALIASES: dict[str, str] = {}


def _key(name: str) -> str:
    """列名の見比べ方: 半角/全角カナ・英数字の幅と大文字小文字をそろえ、空白を除く。"""
    import unicodedata
    return unicodedata.normalize("NFKC", str(name)).casefold().replace(" ", "").replace("　", "")


_CANON: dict[str, str] = {}
for _cols in COLUMNS.values():
    for _c in _cols:
        _CANON.setdefault(_key(_c), _c)


def canonical(cols: list[str]) -> list[str]:
    """2つ目の列名を第1の名前に直す(書き方だけ違う列)。第1と同じ名前・知らない列はそのまま。"""
    have = set(cols)
    out = []
    for c in cols:
        want = ALIASES.get(c) or _CANON.get(_key(c))
        out.append(want if want and want not in have else c)
    return out


def missing(db: str, cols: list[str]) -> list[str]:
    """第1にあって、このファイル(列名を直したあと)に無い列(2つ目の「足りない列」)。"""
    have = set(canonical(list(cols)))
    return [c for c in COLUMNS.get(db, ()) if c not in have and c not in OPTIONAL]
